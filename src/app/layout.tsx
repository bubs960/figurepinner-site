// Self-hosted via next/font (S20 perf audit): the old render-blocking
// fonts.googleapis.com stylesheet cost 100-300ms FCP on every cold visit and
// pulled font files from a second origin. next/font serves woff2 from
// /_next/static (same origin, immutable cache) with size-adjusted fallback
// metrics, so there is no render-blocking CSS and no font layout shift.
// globals.css resolves --font-display/--font-ui through these variables.
const bebas = Bebas_Neue({
  weight: '400',
  subsets: ['latin'],
  variable: '--font-bebas',
  display: 'swap',
})
const inter = Inter({
  subsets: ['latin'],
  variable: '--font-inter',
  display: 'swap',
})
// Cinzel (SIL OFL, Google Fonts) — heroic-poster serif for the MOTU fandom hub
// ONLY. preload:false so the woff2 is fetched only on pages that actually render
// [data-fandom="masters-of-the-universe"] type — zero added weight sitewide (CWV
// guardrail). display:swap + serif fallback keeps the hero title paintable at FCP.
const cinzel = Cinzel({
  weight: ['400', '700', '900'],
  subsets: ['latin'],
  variable: '--font-cinzel',
  display: 'swap',
  preload: false,
  adjustFontFallback: true, // size-adjusted serif fallback → no CLS on the swap
})

